"""从同一关系模型生成 DDL/ERD，初始化模拟数据，演示建表删表及索引。"""
import argparse
import json
import os
import statistics
import time
from pathlib import Path
from datetime import datetime, timedelta
from decimal import Decimal
from sqlalchemy import create_engine, select, insert, func, text, update
from sqlalchemy.schema import CreateTable, CreateIndex
from sqlalchemy.dialects import mysql, mssql
from backend.models import metadata, account, customer, product, warehouse, stock, sales_order, order_item, shipment
from backend.security import hash_password
from backend.validation import string

ROOT = Path(__file__).resolve().parents[2]


def generate():
    data = ROOT / 'data'
    data.mkdir(exist_ok=True)
    for name, dialect in [('mysql', mysql.dialect()), ('sqlserver', mssql.dialect())]:
        statements = ['-- Generated by: python -m tools.manage generate\n-- Run in a NEW, empty database. No DROP statements.']
        for table in metadata.sorted_tables:
            statements.append(str(CreateTable(table).compile(dialect=dialect)).strip() + ';')
            for index in sorted(table.indexes, key=lambda x: x.name):
                statements.append(str(CreateIndex(index).compile(dialect=dialect)).strip() + ';')
        (data / f'schema_{name}.sql').write_text('\n\n'.join(statements)+'\n', encoding='utf-8')
    lines = ['erDiagram']
    for table in metadata.sorted_tables:
        lines.append(f'    {table.name} {{')
        for col in table.columns:
            keys = ['PK'] if col.primary_key else []
            if col.foreign_keys:
                keys.append('FK')
            if col.unique:
                keys.append('UK')
            datatype = str(col.type).split('(')[0].lower()
            lines.append(f'        {datatype} {col.name}' + (' '+','.join(keys) if keys else ''))
        lines.append('    }')
    lines.extend(['    account ||--o{ sales_order : creates', '    customer ||--o{ sales_order : places',
        '    warehouse ||--o{ sales_order : fulfills', '    sales_order ||--|{ order_item : contains',
        '    product ||--o{ order_item : sold_as', '    warehouse ||--o{ stock : holds',
        '    product ||--o{ stock : stocked_at', '    sales_order ||--o| shipment : ships'])
    (data / 'model.mmd').write_text('\n'.join(lines)+'\n', encoding='utf-8')
    print('Generated MySQL / SQL Server DDL and model.mmd from metadata.')


def seed(engine):
    """只向空模型写入，所有初始数据同一事务；没有清空已有业务数据的代码。"""
    passwords = [os.environ['ADMIN_PASSWORD'], os.environ['CLERK_PASSWORD']]
    hashes = [hash_password(p) for p in passwords]
    with engine.begin() as c:
        if any(c.scalar(select(func.count()).select_from(t)) for t in metadata.sorted_tables):
            raise RuntimeError('拒绝初始化非空数据库；请创建独立空库')
        c.execute(insert(account), [{'id': i+1, 'username': name, 'password_hash': hashes[i], 'role': name}
                                    for i, name in enumerate(['admin', 'clerk'])])
        c.execute(insert(customer), [{'id': i, 'name': f'模拟企业客户{i:04}', 'phone': f'TEST-{i:06}',
                                      'address': f'模拟地址：园区{i % 20 + 1}号'} for i in range(1,2001)])
        c.execute(insert(warehouse), [{'id': i, 'name': name} for i, name in enumerate(['广州中心仓','佛山周转仓','深圳前置仓'],1)])
        prices = {i: Decimal(1000+i*7)/100 for i in range(1,1001)}
        c.execute(insert(product), [{'id': i, 'sku': f'SKU-{i:05}', 'name': f'{["办公耗材","智能配件","包装材料","设备备件"][i%4]} {i:04}', 'price': prices[i]} for i in prices])
        c.execute(insert(stock), [{'warehouse_id': w, 'product_id': i, 'quantity': 5000} for w in range(1,4) for i in prices])
        # 历史已履约订单；stock=导入时点结余，不再次扣减历史订单。
        for start in range(1,25001,1000):
            orders, items, shipments = [], [], []
            for i in range(start, start+1000):
                when = datetime(2026,1,1) + timedelta(minutes=i*10)
                orders.append({'id': i, 'request_key': f'00000000-0000-4000-8000-{i:012}', 'customer_id': (i-1)%2000+1,
                               'warehouse_id': (i-1)%3+1, 'created_by': 2, 'status': 'shipped', 'created_at': when})
                for pid in ((i-1)%1000+1, (i+499)%1000+1):
                    items.append({'order_id': i, 'product_id': pid, 'quantity': i%4+1, 'unit_price': prices[pid]})
                shipments.append({'order_id': i, 'tracking_no': f'DEMO-{i:08}', 'shipped_at': when+timedelta(hours=2)})
            c.execute(insert(sales_order), orders)
            c.execute(insert(order_item), items)
            c.execute(insert(shipment), shipments)
    return counts(engine)


def counts(engine):
    with engine.connect() as c:
        result = {t.name: c.scalar(select(func.count()).select_from(t)) for t in metadata.sorted_tables}
    result['total'] = sum(result.values())
    return result


def ddl_demo(engine):
    """DDL 隐式提交：只操作专用实验表，不混同业务事务的原子性。"""
    with engine.connect() as c:
        if c.scalar(text("SELECT COUNT(*) FROM information_schema.tables WHERE table_schema=DATABASE() AND table_name='course_ddl_demo'")):
            raise RuntimeError('实验表已存在，拒绝覆盖；请先检查旧实验结果')
        c.execute(text('CREATE TABLE course_ddl_demo (id INT PRIMARY KEY, note VARCHAR(80) NOT NULL) ENGINE=InnoDB'))
        c.commit()
        try:
            c.execute(text('INSERT INTO course_ddl_demo VALUES (:id, :note)'), {'id':1,'note':'建表与插入'})
            c.execute(text('UPDATE course_ddl_demo SET note=:note WHERE id=:id'), {'id':1,'note':'已修改'})
            value = c.scalar(text('SELECT note FROM course_ddl_demo WHERE id=:id'), {'id':1})
            assert value == '已修改'
            c.execute(text('DELETE FROM course_ddl_demo WHERE id=:id'), {'id':1})
            assert c.scalar(text('SELECT COUNT(*) FROM course_ddl_demo')) == 0
            c.commit()
        finally:
            c.rollback()
            c.execute(text('DROP TABLE course_ddl_demo'))
            c.commit()
        assert not c.scalar(text("SELECT COUNT(*) FROM information_schema.tables WHERE table_schema=DATABASE() AND table_name='course_ddl_demo'"))
    return {'create':True, 'insert':True, 'update':True, 'delete':True, 'drop':True, 'updated_value':value}


def index_demo(engine):
    result = {'iterations':30, 'customer_id':42, 'note':'同数据、同参数、热缓存、单连接；不保证所有环境均加速'}
    sql = 'SELECT id, created_at FROM sales_order {hint} WHERE customer_id=:cid ORDER BY created_at'
    with engine.connect() as c:
        expected = None
        for label, hint in [('without_index','IGNORE INDEX (ix_order_customer_created)'), ('with_index','FORCE INDEX (ix_order_customer_created)')]:
            statement = sql.format(hint=hint)
            plan = [dict(x) for x in c.execute(text('EXPLAIN '+statement), {'cid':42}).mappings()]
            samples = []
            for _ in range(30):
                start = time.perf_counter()
                rows = c.execute(text(statement), {'cid':42}).all()
                samples.append((time.perf_counter()-start)*1000)
            if expected is not None:
                assert rows == expected
            expected = rows
            result[label] = {'plan':plan,'median_ms':statistics.median(samples),'samples_ms':samples,'rows':len(rows)}
    return result


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('action', choices=['generate','seed','counts','ddl-demo','index-demo','set-password','create-user'])
    parser.add_argument('--output', type=Path)
    parser.add_argument('--username')
    parser.add_argument('--role', choices=['admin','clerk'], default='clerk')
    args = parser.parse_args()
    if args.action == 'generate':
        generate()
        return
    engine = create_engine(os.environ['DATABASE_URL'], pool_pre_ping=True)
    if engine.dialect.name != 'mysql':
        raise RuntimeError('课程实验需要真实 MySQL')
    if args.action == 'create-user':
        result = create_user(engine, args.username, os.environ['NEW_PASSWORD'], args.role)
    elif args.action == 'set-password':
        if not args.username:
            parser.error('set-password 需要 --username')
        with engine.begin() as c:
            changed = c.execute(update(account).where(account.c.username == args.username).values(password_hash=hash_password(os.environ['NEW_PASSWORD'])))
            if changed.rowcount != 1:
                raise RuntimeError('账户不存在')
        result = {'updated':args.username}
    else:
        result = {'seed':seed,'counts':counts,'ddl-demo':ddl_demo,'index-demo':index_demo}[args.action](engine)
    content = json.dumps(result, ensure_ascii=False, indent=2, default=str)
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(content+'\n', encoding='utf-8')
    print(content)


def create_user(engine, username, password, role='clerk'):
    username = string(username, '用户名', 40)
    if role not in ('admin', 'clerk'):
        raise ValueError('角色必须为 admin 或 clerk')
    hashed = hash_password(password)
    with engine.begin() as conn:
        result = conn.execute(insert(account).values(username=username, password_hash=hashed, role=role))
    return {'id': result.inserted_primary_key[0], 'username': username, 'role': role}


if __name__ == '__main__':
    main()
